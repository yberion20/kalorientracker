function parsePortions(s: string): Portion[] {
  return s
    .split("|")
    .map((p) => p.split(":"))
    .filter(([l, a]) => l && a)
    .map(([label, amount]) => ({ label, amount: Number(amount) }));
}

export interface GenericFood {
  food: FoodSnapshot;
  synonyms: string;
}

